function startOfDay(date) {
  return new Date(date.getFullYear(), date.getMonth(), date.getDate());
}

function dateKey(date) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(
    date.getDate(),
  ).padStart(2, "0")}`;
}

function addDays(date, days) {
  return new Date(date.getFullYear(), date.getMonth(), date.getDate() + days);
}

function todayDate() {
  return startOfDay(new Date());
}

function spokenDate() {
  return addDays(todayDate(), 1);
}

function scheduleMap() {
  const dict = copy[state.lang];
  const today = todayDate();
  const map = new Map([
    [dateKey(today), dict.eventsToday],
    [dateKey(addDays(today, -1)), dict.eventsYesterday],
    [dateKey(addDays(today, 1)), dict.eventsTomorrow],
    [dateKey(addDays(today, 3)), dict.eventsLater],
  ]);
  if (state.spokenAdded) {
    const key = dateKey(spokenDate());
    map.set(key, [...(map.get(key) ?? []), { ...dict.spoken, fresh: true }]);
  }
  return map;
}

function eventsFor(date) {
  return scheduleMap().get(dateKey(date)) ?? [];
}

