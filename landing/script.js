let scrollToken = 0;

function animateScrollTo(top, done) {
  const token = ++scrollToken;
  const start = window.scrollY;
  const dist = top - start;
  if (Math.abs(dist) < 2 || prefersReducedMotion()) {
    window.scrollTo(0, top);
    if (token === scrollToken) done?.();
    return;
  }
  const duration = Math.min(780, Math.max(460, Math.abs(dist) * 0.4));
  const origin = performance.now();
  const ease = (t) => 1 - (1 - t) ** 3;
  const step = (now) => {
    if (token !== scrollToken) return;
    const p = Math.min(1, (now - origin) / duration);
    window.scrollTo(0, start + dist * ease(p));
    if (p < 1) window.requestAnimationFrame(step);
    else done?.();
  };
  window.requestAnimationFrame(step);
}

function cancelAnimatedScroll() {
  scrollToken += 1;
}

function bindSmoothAnchors() {
  document.querySelectorAll('a[href^="#"]').forEach((link) => {
    link.addEventListener("click", (event) => {
      if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
      const raw = (link.getAttribute("href") || "").slice(1);
      const id = raw === "open" ? "product" : raw;
      if (!id) return;
      const target = document.getElementById(id);
      if (!target) return;
      event.preventDefault();
      const nav =
        parseFloat(getComputedStyle(document.documentElement).getPropertyValue("--nav-h")) || 72;
      const top = Math.max(0, target.getBoundingClientRect().top + window.scrollY - nav);
      animateScrollTo(top);
      history.pushState(null, "", `#${id}`);
    });
  });
}

function prefersReducedMotion() {
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

function startHeadline() {
  const dict = copy[state.lang];
  const lines = [
    { node: document.getElementById("h1a"), value: dict.h1a },
    { node: document.getElementById("h1b"), value: dict.h1b },
  ];
  document.getElementById("headline").setAttribute("aria-label", `${dict.h1a}${dict.h1b}`);
  window.clearTimeout(headline.timer);
  const token = ++headline.token;
  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  lines.forEach((line, index) => {
    line.node.textContent = reduced ? line.value : "";
    line.node.classList.toggle("has-caret", !reduced && index === 0);
  });
  if (reduced) return;

  let lineIndex = 0;
  let charIndex = 0;
  let mode = "type";
  const typeDelay = (text) => (/[\u4e00-\u9fff]/.test(text) ? 92 : 56);
  const setCaret = (index) => {
    lines.forEach((line, i) => line.node.classList.toggle("has-caret", i === index));
  };

  const step = () => {
    if (token !== headline.token) return;
    if (mode === "type") {
      const line = lines[lineIndex];
      const chars = Array.from(line.value);
      if (charIndex < chars.length) {
        line.node.textContent += chars[charIndex];
        charIndex += 1;
        headline.timer = window.setTimeout(step, typeDelay(line.value));
        return;
      }
      if (lineIndex < lines.length - 1) {
        lineIndex += 1;
        charIndex = 0;
        setCaret(lineIndex);
        headline.timer = window.setTimeout(step, 320);
        return;
      }
      mode = "delete";
      headline.timer = window.setTimeout(step, 2400);
      return;
    }

    const current = lines[lineIndex];
    const typed = Array.from(current.node.textContent);
    if (typed.length > 0) {
      current.node.textContent = typed.slice(0, -1).join("");
      headline.timer = window.setTimeout(step, 28);
      return;
    }
    if (lineIndex > 0) {
      lineIndex -= 1;
      setCaret(lineIndex);
      headline.timer = window.setTimeout(step, 70);
      return;
    }
    mode = "type";
    charIndex = 0;
    setCaret(0);
    headline.timer = window.setTimeout(step, 420);
  };

  headline.timer = window.setTimeout(step, 80);
}

