function bindReadingSnap() {
  if (prefersReducedMotion()) return;
  const pin = document.getElementById("slogan-pin");
  let idle = 0;
  let snapping = false;
  let touching = false;

  const insideDemoTravel = (y) => {
    if (!pin) return false;
    const nav = navOffset();
    const start = pin.getBoundingClientRect().top + window.scrollY - nav;
    const end = start + pin.offsetHeight - (window.innerHeight - nav);
    const edge = Math.min(140, window.innerHeight * 0.14);
    return y > start + edge && y < end - edge;
  };

  const settle = () => {
    if (snapping || touching || slogan.hold || prefersReducedMotion()) return;
    const y = window.scrollY;
    if (insideDemoTravel(y)) return;
    const reach = window.innerHeight * 0.34;
    let best = null;
    let dist = Infinity;
    readingSnapPoints().forEach((point) => {
      const d = Math.abs(y - point.top);
      if (d < dist) {
        dist = d;
        best = point;
      }
    });
    if (!best || dist < 8 || dist > reach) return;
    snapping = true;
    animateScrollTo(best.top, () => {
      snapping = false;
    });
  };

  const ping = () => {
    if (snapping || slogan.hold) return;
    window.clearTimeout(idle);
    idle = window.setTimeout(settle, 90);
  };

  window.addEventListener("scroll", ping, { passive: true });
  window.addEventListener("wheel", ping, { passive: true });
  window.addEventListener(
    "touchstart",
    () => {
      touching = true;
      window.clearTimeout(idle);
    },
    { passive: true },
  );
  window.addEventListener(
    "touchend",
    () => {
      touching = false;
      ping();
    },
    { passive: true },
  );
}

function bindReveals() {
  const nodes = document.querySelectorAll(".reveal");
  if (prefersReducedMotion() || typeof IntersectionObserver === "undefined") {
    nodes.forEach((node) => node.classList.add("is-in"));
    return;
  }
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-in");
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.14, rootMargin: "0px 0px -8% 0px" },
  );
  nodes.forEach((node) => observer.observe(node));
}

